# Dependabot cannot compute `target-branch`, so regenerate the docker entries
# in .github/dependabot.yml for the currently supported release branches.
# The runtime base image is run-jammy-tiny on older branches and
# ubuntu-noble-run-tiny from the branch `main` is on, so both are allowed.
#
# Supported branches are the newest SUPPORTED_MINORS minor versions that have
# a GA `vX.Y.0` tag (pre-release tags such as `vX.Y.0-rc.1` do not count), so a
# `release-X.Y` branch is not picked up before X.Y.0 is released.
#
# Only the lines between the BEGIN and END markers in dependabot.yml are
# rewritten. Run from the repository root; this is a no-op when the file is
# already up to date.

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/velero-io/velero.git}"
DEPENDABOT_FILE="${DEPENDABOT_FILE:-.github/dependabot.yml}"
SUPPORTED_MINORS="${SUPPORTED_MINORS:-2}"

BEGIN_MARKER="  # BEGIN generated by hack/update-dependabot-release-branches.sh, do not edit by hand"
END_MARKER="  # END generated by hack/update-dependabot-release-branches.sh"

# Newest first, e.g. "1.18" then "1.17".
minors=$(git ls-remote --tags --refs "${REPO_URL}" 'v*.*.0' |
    sed -n 's#.*refs/tags/v\([0-9][0-9]*\.[0-9][0-9]*\)\.0$#\1#p' |
    sort -t. -k1,1nr -k2,2nr -u |
    head -n "${SUPPORTED_MINORS}")

if [[ -z "${minors}" ]]; then
    echo "no GA release tags found in ${REPO_URL}" >&2
    exit 1
fi

if ! grep -qxF "${BEGIN_MARKER}" "${DEPENDABOT_FILE}" || ! grep -qxF "${END_MARKER}" "${DEPENDABOT_FILE}"; then
    echo "${DEPENDABOT_FILE} is missing the BEGIN/END markers" >&2
    exit 1
fi

generated=$(mktemp)
output=$(mktemp)
trap 'rm -f "${generated}" "${output}"' EXIT

for minor in ${minors}; do
    cat >>"${generated}" <<EOF
  - package-ecosystem: "docker"
    directory: "/"
    target-branch: "release-${minor}"
    schedule:
      interval: "weekly"
    allow:
      - dependency-name: "paketobuildpacks/run-jammy-tiny"
      - dependency-name: "paketobuildpacks/ubuntu-noble-run-tiny"
    ignore:
      - dependency-name: "*"
        update-types: ["version-update:semver-major", "version-update:semver-minor"]
    labels:
      - "Dependencies"
      - "kind/changelog-not-required"
    commit-message:
      prefix: "[release-${minor}]"
EOF
done

awk -v begin="${BEGIN_MARKER}" -v end="${END_MARKER}" -v generated="${generated}" '
    $0 == begin {
        print
        while ((getline line < generated) > 0) print line
        skipping = 1
        next
    }
    $0 == end { skipping = 0 }
    !skipping { print }
' "${DEPENDABOT_FILE}" >"${output}"

cat "${output}" >"${DEPENDABOT_FILE}"
echo "supported release branches: $(echo "${minors}" | sed 's/^/release-/' | paste -sd, -)"
